#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { isDeepStrictEqual } from "node:util";
import {
  catalogThemeName, cssTokenDeclaration, parseCssTokenBlock, readMarkdownFencedSections,
  readStyleRenderArchetype, readStyleThemeTokens, stripCssComments,
} from "./assets/effects/protocol.mjs";

const styleDirectory = "references/catalogs/styles";
const authorDirectory = "references/style-sources";
const generatedStyle = /^---[ \t]*\n([\s\S]*?)\n---[ \t]*\n\n(<!-- Generated by sync_renders\.py from references\/style-sources\/\. -->\n)(?:<!-- Style build SHA-256: ([a-f0-9]{64}) -->\n)?/;
const cssBlockBody = String.raw`((?:"(?:\\[\s\S]|[^"\\])*"|'(?:\\[\s\S]|[^'\\])*'|[^}"'])*)\}`;
const htmlEntities = { "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": '"', "&#x27;": "'" };

const sourcesOnly = process.argv[2] === "--style-sources";
const root = sourcesOnly ? "renders" : process.argv[2] || "renders";
const sourceProblems = path.resolve(root) === path.resolve("renders") ? checkStyleArtifacts(root) : [];
if (sourcesOnly || sourceProblems.length) {
  for (const problem of sourceProblems) console.error(problem);
  process.exit(sourceProblems.length ? 1 : 0);
}
const sharedPreviewCss = fs.readFileSync("assets/catalog-preview.css", "utf8");
const requiredTokens = [
  "--dig-bg",
  "--dig-surface",
  "--dig-surface-strong",
  "--dig-text",
  "--dig-text-muted",
  "--dig-accent",
  "--dig-border",
  "--dig-radius-md",
  "--dig-text-5xl",
];
const forbiddenRuntimeCopy = [
  "Deploy Agents With Control",
  "Agent Execution Overview",
  "Open Console",
  "Execution Trace",
  "Queue: 24",
  "Region: HKG-1",
];

function catalogSlugs(dir, recursive = false) {
  const slugs = new Set();
  if (!fs.existsSync(dir)) return slugs;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true, recursive })) {
    if (!entry.isFile() || !entry.name.endsWith(".md") || /\.(en|zh-CN)\.md$/.test(entry.name)
        || ["README.md", "_template.md"].includes(entry.name)) continue;
    slugs.add(path.basename(entry.name, ".md"));
  }
  return slugs;
}

function checkStyleArtifacts(renderRoot) {
  const problems = [];
  const sources = new Map([...catalogSlugs(styleDirectory)].map(slug => [
    slug, fs.readFileSync(path.join(styleDirectory, `${slug}.md`), "utf8").replace(/\r\n?/g, "\n"),
  ]));
  const authors = catalogSlugs(authorDirectory);
  for (const slug of authors) {
    if (!sources.has(slug)) {
      problems.push(`${styleDirectory}/${slug}.md is missing its generated Catalog Markdown. Run a full render build.`);
    }
  }

  const previews = path.join(renderRoot, "styles");
  const expected = new Map();
  for (const [slug, markdown] of sources) {
    const source = path.join(styleDirectory, `${slug}.md`);
    const preview = path.join(previews, `${slug}.html`);
    const generated = markdown.match(generatedStyle);
    const parent = generated?.[1].match(/^derived_from: ([a-z0-9]+(?:-[a-z0-9]+)*)[ \t]*$/m)?.[1];
    if (authors.has(slug)) {
      const author = fs.readFileSync(path.join(authorDirectory, `${slug}.md`), "utf8").replace(/\r\n?/g, "\n");
      const parentMarkdown = sources.get(parent);
      const fingerprint = generated?.[3];
      if (!fingerprint || !parentMarkdown || authors.has(parent) || fingerprint !== createHash("sha256")
          .update([author, parentMarkdown, markdown.replace(`<!-- Style build SHA-256: ${fingerprint} -->\n`, "")].join("\0"))
          .digest("hex")) {
        problems.push(`${source} is stale or has an invalid parent. Run a full render build.`);
      }
    } else if (generated || /^derived_from:/m.test(markdown.match(/^---[ \t]*\n([\s\S]*?)\n---[ \t]*$/m)?.[1] ?? "")) {
      problems.push(`${source} has no author source. Remove the retired Catalog Markdown or restore its source.`);
    }
    try {
      const { light, dark } = readStyleThemeTokens(markdown, source);
      if (!light["--dig-bg"] || !dark["--dig-bg"]) {
        problems.push(`${source} is missing canonical light or dark style tokens.`);
        continue;
      }
      const theme = { light, dark: { ...light, ...dark } };
      const name = catalogThemeName(markdown, slug);
      expected.set(slug, { theme, parent, name });
      if (!fs.existsSync(preview)) {
        problems.push(`${preview} is missing. Run a full render build.`);
        continue;
      }
      const html = fs.readFileSync(preview, "utf8").replace(/\r\n?/g, "\n");
      const body = html.match(/<body(?:\s[^>]*)?>/i)?.[0] ?? "";
      const lab = html.match(/<section\s[^>]*\bid="style-lab"[^>]*>/i)?.[0] ?? "";
      const styleContract = readMarkdownFencedSections(markdown, { "Style Contract": "yaml" })["Style Contract"]
        ?.replace(/[ \t]+\n/g, "\n");
      const archetype = readStyleRenderArchetype(markdown);
      if (!styleContract || !archetype) {
        problems.push(`${source} is missing its Style Contract or render.archetype.`);
      } else if (readHtmlAttribute(lab, "data-style-contract") !== styleContract
                 || readHtmlAttribute(body, "data-render-archetype") !== archetype) {
        problems.push(`${preview} has a stale Style Contract or render archetype. Run a full render build.`);
      } else if (readHtmlAttribute(body, "data-style-source-sha256") !== createHash("sha256").update(markdown).digest("hex")) {
        problems.push(`${preview} was built from different style Markdown. Run a full render build.`);
      }

      const head = html.match(/<head>([\s\S]*?)<\/head>/i)?.[1] ?? "";
      const lightRoot = parseRoot(head);
      const darkRoot = parseRoot(head, String.raw`html\[data-style-theme="dark"\]`);
      if (lightRoot.count !== 1 || darkRoot.count !== 1
          || !isDeepStrictEqual(lightRoot.tokens, light) || !isDeepStrictEqual(darkRoot.tokens, dark)
          || !isDeepStrictEqual(parseCssTokenBlock(readHtmlAttribute(lab, "data-style-token-block")), light)
          || !isDeepStrictEqual(parseCssTokenBlock(readHtmlAttribute(lab, "data-style-dark-token-block")), theme.dark)) {
        problems.push(`${preview} has stale style tokens. Run a full render build.`);
      }
    } catch (error) {
      problems.push(`${source} or ${preview} has invalid style data: ${error.message}`);
    }
  }

  if (fs.existsSync(previews)) {
    for (const entry of fs.readdirSync(previews, { withFileTypes: true })) {
      if (entry.isDirectory() || !entry.name.endsWith(".html") || ["index.html", "README.html"].includes(entry.name)) continue;
      if (!sources.has(path.basename(entry.name, ".html"))) {
        problems.push(`${path.join(previews, entry.name)} has no style source. Remove the retired preview before packaging.`);
      }
    }
  }

  const index = path.join(renderRoot, "index.html");
  if (fs.existsSync(index)) {
    try {
      const registry = JSON.parse(fs.readFileSync(index, "utf8")
        .match(/const catalogData = (\{[\s\S]*?\});\s*(?:function getCatalogItems|\/\/ Compute)/)?.[1]);
      const lists = ["items", "brands"].filter(list => Array.isArray(registry.styles?.[list]));
      if (!lists.length && sources.size) problems.push(`${index} is missing the style registry. Run a full render build.`);
      for (const list of lists) {
        const entries = new Set();
        for (const item of registry.styles[list]) {
          if (entries.has(item.slug)) problems.push(`${index} styles.${list} repeats ${item.slug}. Run a full render build.`);
          entries.add(item.slug);
          if (!sources.has(item.slug)) {
            problems.push(`${index} styles.${list} contains retired style ${item.slug}. Run a full render build.`);
          } else if (item.link !== `./styles/${item.slug}.html`
                     || !fs.statSync(path.join(previews, `${item.slug}.html`), { throwIfNoEntry: false })?.isFile()) {
            problems.push(`${index} has no valid preview link for style ${item.slug}. Run a full render build.`);
          } else if (expected.has(item.slug)) {
            const { theme, parent, name } = expected.get(item.slug);
            const catalogName = value => value.trim().replace(/^["']+|["']+$/g, "");
            if (item.bg !== theme.light["--dig-bg"] || item.accent !== theme.light["--dig-accent"]
                || item.derived_from !== parent
                || (name.en !== item.slug && item.name_en !== catalogName(name.en))
                || (name["zh-CN"] !== item.slug && item.name_zh !== catalogName(name["zh-CN"]))) {
              problems.push(`${index} styles.${list} has stale data for ${item.slug}. Run a full render build.`);
            }
          }
        }
        for (const slug of sources.keys()) {
          if (!entries.has(slug)) problems.push(`${index} styles.${list} is missing ${slug}. Run a full render build.`);
        }
      }
    } catch (error) {
      problems.push(`${index} has invalid catalogData: ${error.message}`);
    }
  } else if (sources.size) {
    problems.push(`${index} is missing. Run a full render build.`);
  }

  const effectPreview = path.join(renderRoot, "effects/index.html");
  if (fs.existsSync(effectPreview)) {
    try {
      const payload = JSON.parse(fs.readFileSync(effectPreview, "utf8")
        .match(/<script id="effect-data" type="application\/json">([\s\S]*?)<\/script>/)?.[1]);
      const activeCatalogs = catalogSlugs("references/catalogs", true);
      const themes = new Map();
      for (const { id, name, theme_tokens: theme } of payload.themes) {
        if (themes.has(id) && sources.has(id)) problems.push(`${effectPreview} repeats style theme ${id}. Run a full render build.`);
        if (!activeCatalogs.has(id)) problems.push(`${effectPreview} contains retired theme ${id}. Run a full render build.`);
        themes.set(id, { name, theme });
      }
      for (const slug of sources.keys()) {
        if (!themes.has(slug)) problems.push(`${effectPreview} is missing style theme ${slug}. Run a full render build.`);
        else if (expected.has(slug)) {
          const { theme, name } = expected.get(slug);
          if (!isDeepStrictEqual(themes.get(slug), { theme, name })) {
            problems.push(`${effectPreview} has stale style theme ${slug}. Run a full render build.`);
          }
        }
      }
    } catch (error) {
      problems.push(`${effectPreview} has invalid theme data: ${error.message}`);
    }
  } else if (sources.size) {
    problems.push(`${effectPreview} is missing. Run a full render build.`);
  }

  const styleRoot = path.resolve(styleDirectory);
  for (const base of ["SKILL", "references/catalogs/README", `${styleDirectory}/README`]) {
    for (const suffix of [".md", ".en.md", ".zh-CN.md"]) {
      const route = base + suffix;
      if (!fs.existsSync(route)) continue;
      const content = fs.readFileSync(route, "utf8");
      for (const [, link] of content.matchAll(/\]\(<?([^\s<>()#]+\.md)(?:#[^\s<>()]+)?>?(?=[\s)])/g)) {
        const target = path.resolve(path.dirname(route), link);
        if (path.dirname(target) === styleRoot && !fs.lstatSync(target, { throwIfNoEntry: false })?.isFile()) {
          problems.push(`${route} links to missing built-in style ${link}. Update the style routing before packaging.`);
        }
      }
    }
  }

  const manifest = "references/shared/catalog-manifest.yaml";
  if (fs.existsSync(manifest)) {
    const entries = fs.readFileSync(manifest, "utf8").split(/^  - slug: /m).slice(1);
    for (const entry of entries) {
      if (!/^    kind: style-catalog[ \t]*\r?$/m.test(entry)) continue;
      const slug = entry.split("\n", 1)[0].trim();
      if (!sources.has(slug)) {
        problems.push(`${manifest} declares missing built-in style ${slug}. Update the manifest before packaging.`);
      } else if (expected.has(slug)) {
        const parent = entry.match(/^    derived_from:[ \t]*([^\r\n]+)$/m)?.[1].trim();
        if (parent !== expected.get(slug).parent) {
          problems.push(`${manifest} has a stale parent for ${slug}. Update the manifest before packaging.`);
        }
      }
    }
  }
  return problems;
}

function readHtmlAttribute(tag, name) {
  return (tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1] ?? "")
    .replace(/&(?:amp|lt|gt|quot|#x27);/g, entity => htmlEntities[entity]);
}

function selectorRule(selector) {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = sharedPreviewCss.match(new RegExp(`${escaped}\\s*\\{([\\s\\S]*?)\\}`, "m"));
  return match?.[1] || "";
}

function walk(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  return entries.flatMap((entry) => {
    const filePath = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(filePath);
    if (!entry.isFile() || !entry.name.endsWith(".html")) return [];
    if (entry.name === "index.html" || entry.name === "README.html") return [];
    if (filePath.includes(`${path.sep}layouts${path.sep}`)) return [];
    if (filePath.includes(`${path.sep}blocks${path.sep}`)) return [];
    return [filePath];
  });
}

function parseRoot(content, selector = ":root") {
  const blocks = [...content.matchAll(new RegExp(`${selector}\\s*\\{${cssBlockBody}`, "g"))];
  if (!blocks.length) return { tokens: {}, raw: "", unexpected: [], count: 0 };
  const raw = stripCssComments(blocks[0][1]);
  const tokens = parseCssTokenBlock(raw);
  const unexpected = raw.replace(cssTokenDeclaration, "").split("\n").map(line => line.trim())
    .filter(line => line && !/^color-scheme: (?:dark|light|light dark);$/.test(line));
  return { tokens, raw, unexpected, count: blocks.length };
}

function hexToRgb(value) {
  const hex = value.trim().match(/^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/);
  if (!hex) return null;
  const raw = hex[1].length === 3
    ? hex[1].split("").map((char) => char + char).join("")
    : hex[1];
  const int = Number.parseInt(raw, 16);
  return [(int >> 16) & 255, (int >> 8) & 255, int & 255];
}

function luminance(rgb) {
  const channel = rgb.map((value) => {
    const normalized = value / 255;
    return normalized <= 0.03928
      ? normalized / 12.92
      : ((normalized + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * channel[0] + 0.7152 * channel[1] + 0.0722 * channel[2];
}

function contrast(a, b) {
  const rgbA = hexToRgb(a);
  const rgbB = hexToRgb(b);
  if (!rgbA || !rgbB) return null;
  const lumA = luminance(rgbA);
  const lumB = luminance(rgbB);
  const lighter = Math.max(lumA, lumB);
  const darker = Math.min(lumA, lumB);
  return (lighter + 0.05) / (darker + 0.05);
}

const files = walk(root);
const problems = [];

const baseCanvasRule = [...sharedPreviewCss.matchAll(/^body\s*\{([^}]+)\}/gm)]
  .map(match => match[1]).find(rule => rule.includes("font-family:")) || "";
if (!/background:\s*var\(--dig-bg\)\s*;/.test(baseCanvasRule) || /gradient\(/.test(baseCanvasRule)) {
  problems.push("assets/catalog-preview.css: default preview canvas must use the catalog's solid --dig-bg");
}
if (!/content:\s*none\s*;/.test(selectorRule("body::before"))) {
  problems.push("assets/catalog-preview.css: default preview canvas must not generate a decorative grid overlay");
}

for (const selector of [".palette-lab-row", ".palette-lab-input", ".palette-candidate"]) {
  const rule = selectorRule(selector);
  if (!rule) {
    problems.push(`assets/catalog-preview.css: missing shared Lab rule ${selector}`);
    continue;
  }
  if (/background:\s*var\(--dig-control-bg(?:-hover)?\)/.test(rule)) {
    problems.push(`assets/catalog-preview.css: ${selector} uses --dig-control-bg directly and can create unreadable dark-mode Lab content`);
  }
}

for (const match of sharedPreviewCss.matchAll(/\.palette-(?:lab-row|lab-input|candidate)[^{]*\{([\s\S]*?)\}/g)) {
  if (/background:\s*var\(--dig-control-bg(?:-hover)?\)/.test(match[1])) {
    problems.push("assets/catalog-preview.css: a Lab surface state uses --dig-control-bg directly and can create unreadable dark-mode content");
  }
}

for (const filePath of files) {
  const content = fs.readFileSync(filePath, "utf8");
  const rel = path.relative(process.cwd(), filePath);
  // Effect Lab has its own schema/runtime/browser validation, and is not a catalog.
  if (rel.replaceAll(path.sep, '/').endsWith('renders/effects/index.html')) continue;
  const { tokens, raw, unexpected } = parseRoot(content);

  if (!raw) {
    problems.push(`${rel}: missing :root token block`);
    continue;
  }

  for (const line of unexpected) {
    problems.push(`${rel}: unexpected :root line "${line}"`);
  }

  for (const token of requiredTokens) {
    if (!tokens[token]) problems.push(`${rel}: missing required token ${token}`);
  }

  const bgText = contrast(tokens["--dig-bg"] || "", tokens["--dig-text"] || "");
  if (bgText !== null && bgText < 4.5) {
    problems.push(`${rel}: --dig-bg / --dig-text contrast ${bgText.toFixed(2)} is below 4.5`);
  }

  const surfaceText = contrast(tokens["--dig-surface"] || "", tokens["--dig-text"] || "");
  if (surfaceText !== null && surfaceText < 4.5) {
    problems.push(`${rel}: --dig-surface / --dig-text contrast ${surfaceText.toFixed(2)} is below 4.5`);
  }

  const archetypeMatch = content.match(/data-render-archetype="([^"]+)"/);
  const archetype = archetypeMatch?.[1] || "token-sheet";
  const isStyleRender = rel.split(path.sep).includes("styles");
  if (
    isStyleRender
    && /body::before\s*\{[\s\S]*?#52525b[\s\S]*?background-size:\s*8px\s+8px;[\s\S]*?\}/.test(content)
  ) {
    problems.push(`${rel}: style render contains legacy hard-coded body::before background override`);
  }
  if (archetype !== "token-sheet") {
    for (const phrase of forbiddenRuntimeCopy) {
      if (content.includes(phrase)) {
        problems.push(`${rel}: archetype render still contains default runtime copy "${phrase}"`);
      }
    }
  }
}

if (problems.length) {
  console.error(`Catalog render validation failed with ${problems.length} issue(s):`);
  for (const problem of problems) console.error(`- ${problem}`);
  process.exit(1);
}

console.log(`Catalog render validation passed for ${files.length} preview(s).`);
